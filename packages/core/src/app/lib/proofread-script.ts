function build(): { toTraditional: Map<string, string>; toSimplified: Map<string, string> } {
  const toTraditional = new Map<string, string>();
  const toSimplified = new Map<string, string>();
  for (const pair of PAIRS.split(/\s+/)) {
    const [simplified, traditional] = Array.from(pair);
    if (!simplified || !traditional) continue;
    toTraditional.set(simplified, traditional);
    toSimplified.set(traditional, simplified);
  }
  return { toTraditional, toSimplified };
}

export const { toTraditional: SIMPLIFIED_ONLY, toSimplified: TRADITIONAL_ONLY } = build();
